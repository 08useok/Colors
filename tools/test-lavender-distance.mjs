import assert from 'node:assert/strict';
import { BETA_CHARACTERS } from '../src/config/beta-characters.js';
import { applyBeta7Balance } from '../src/config/beta7-balance.js';
import { createBeta6Combat } from '../src/combat/beta6-combat.js';
const config = applyBeta7Balance(BETA_CHARACTERS);
const run = (world, seconds) => { for (let i=0;i<seconds*60;i++) world.update(1/60); };
const close = (actual, expected) => assert.ok(Math.abs(actual-expected)<1e-8, `${actual} != ${expected}`);
for (const [distance, expected] of [[0,1100],[4.5,1375],[9,1650]]) {
  const events = [];
  const world = createBeta6Combat(config,{aimError:0,onEvent(e){if(e.type==='damage')events.push(e);}});
  const lavender = world.add('lavender',{automatic:false,team:1,next:0});
  const enemy = world.add('red',{automatic:false,team:2,x:distance,hp:100000});
  world.fire(lavender,enemy,0);
  run(world,2);
  assert.equal(events.length,3);
  for (const e of events) close(e.amount,expected);
  for (let i=1;i<events.length;i++) close(events[i].time-events[i-1].time,.5);
  close(lavender.charge,2);
}
// Distance belongs to the emitted cloud: walking away must not raise its damage.
const world = createBeta6Combat(config,{aimError:0});
const owner = world.add('lavender',{automatic:false,next:0,team:1});
const enemy = world.add('red',{automatic:false,x:4.5,hp:100000,team:2});
world.fire(owner,enemy,0);
owner.x=20;
run(world,.25);
close(100000-enemy.hp,1375);
enemy.x=9;
run(world,.5);
close(100000-enemy.hp,1375+1650);
const field = createBeta6Combat(config);
const caster = field.add('lavender',{automatic:false,team:1,charge:6});
const target = field.add('red',{automatic:false,team:2,x:2,hp:100000});
field.cast(caster,target,{angle:0});
field.update(1/60);
close(target.slow,.7);
close(caster.charge,.025);
target.x=10;
run(field,.1);
assert(target.slowUntil<field.time,'slow expires outside the field');
assert.equal(BETA_CHARACTERS.lavender.special.slowPercent,.3,'other seasons keep base slow');
assert.equal(BETA_CHARACTERS.lavender.sprayDistanceDamageBonus,undefined);
const outside = createBeta6Combat(config,{aimError:0});
const shooter = outside.add('lavender',{automatic:false,next:0});
const outOfRange = outside.add('red',{automatic:false,x:9.01,hp:100000});
outside.fire(shooter,outOfRange,0);
run(outside,2);
close(outOfRange.hp,100000);
console.log('PASS: distance-scaled damage, fixed cloud origin, per-tick distance, hit/charge cap and 70% field slow.');
