import assert from 'node:assert/strict';
import {BETA_CHARACTERS} from '../src/config/beta-characters.js';
import {applyBeta6Balance} from '../src/config/beta6-balance.js';
import {applyBeta7Balance} from '../src/config/beta7-balance.js';
import {createBeta6Combat} from '../src/combat/beta6-combat.js';
const config=applyBeta7Balance(BETA_CHARACTERS);
assert.equal(config.yellow.shockDuration,3);
assert.equal(applyBeta6Balance(BETA_CHARACTERS).yellow.shockDuration,2);
const events=[];
const world=createBeta6Combat(config,{bounds:100,onEvent:e=>events.push(e)});
const a=world.add('yellow',{automatic:false,next:0,charge:2});
const b=world.add('ivory',{automatic:false,x:40,hp:100000});
assert(world.cast(a,b,{point:{x:6,z:2},angle:0}));
assert.equal(a.devices.length,0,'thrown device is not installed yet');
for(let i=0;i<70;i++)world.update(1/60);
assert.equal(a.devices.length,1);
a.automatic=true;a.next=world.time;a.ammo=3;
world.update(1/60);
assert.equal(a.attackCount,0,'one device does not trigger circuit targeting');
a.automatic=false;a.charge=2;
assert(world.cast(a,b,{point:{x:6,z:-2},angle:0}));
for(let i=0;i<70;i++)world.update(1/60);
assert.equal(a.devices.length,2);
a.automatic=true;a.next=world.time;a.ammo=3;
world.update(1/60);
assert(a.attackCount>0,'bot shoots installed device even when enemy is outside attack range');
for(let i=0;i<80;i++)world.update(1/60);
assert(events.some(e=>e.type==='circuit'),'device shot activates circuit');

const manual=createBeta6Combat(config,{bounds:100});
const player=manual.add('yellow',{automatic:false,next:0,devices:[{x:0,z:6},{x:0,z:-6}]});
const enemy=manual.add('ivory',{automatic:false,x:6});
assert(manual.fire(player,enemy,0));
assert.equal(manual.projectiles[0].yaw,0,'manual aim is never redirected to devices');
for(let i=0;i<40;i++)manual.update(1/60);
assert(enemy.slowUntil-manual.time>2,'orb applies the longer three-second slow');

const distant=createBeta6Combat(config,{bounds:100});
const bot=distant.add('yellow',{next:0,hp:1000,devices:[{x:20,z:0},{x:22,z:0}]});
distant.add('ivory',{x:50,automatic:false,hp:100000});
for(let i=0;i<200;i++)distant.update(1/60);
assert(bot.attackCount>0,'out-of-range bot approaches device and activates it');
console.log('PASS: 3-second slow, two installed casts, device targeting outside enemy range, approach and manual aiming');
