import assert from 'node:assert/strict';
import {BETA_CHARACTERS} from '../src/config/beta-characters.js';
import {applyBeta6Balance} from '../src/config/beta6-balance.js';
import {applyBeta7Balance} from '../src/config/beta7-balance.js';
import {createBeta6Combat} from '../src/combat/beta6-combat.js';
import {beta6Duel} from './simulate-beta6-balance.mjs';
const config=applyBeta7Balance(BETA_CHARACTERS);
const events=[];
const world=createBeta6Combat(config,{bounds:40,onEvent:e=>{if(e.type==='damage')events.push(e);}});
const gold=world.add('gold',{automatic:false,team:1,charge:6});
const enemy=world.add('red',{automatic:false,team:2,x:2,hp:100000});
assert(world.cast(gold,enemy));
for(let i=0;i<10;i++)world.update(1/60);
assert.equal(events.length,0,'no damage before activation delay');
for(let i=0;i<5;i++)world.update(1/60);
assert.equal(events.length,1,'field activates between 0.2 and 0.25 seconds');
assert.equal(events[0].amount,100);
assert.equal(gold.charge,0,'field does not recharge ultimate');
assert.equal(applyBeta6Balance(BETA_CHARACTERS).gold.ultimate.delay,.35,'season 6 unchanged');
const retreat=createBeta6Combat(config,{bounds:40});
const lowGold=retreat.add('gold',{x:0,hp:config.gold.maxHealth*.4,next:100});
retreat.add('green',{x:7,hp:config.green.maxHealth*.4,next:100});
retreat.update(1/60);
assert(lowGold.x<0,'pursuit removed; ordinary low-health retreat restored');
const before=structuredClone(config);before.gold.ultimate.delay=.35;
const scenario={distance:10,aimError:.1,bounds:40,level:6};
const old=beta6Duel(before,'gold','green',scenario,20270939,-1);
const fixed=beta6Duel(config,'gold','green',scenario,20270939,-1);
assert.equal(old.outcome,-1,'historical loss reproduced');
assert.equal(fixed.outcome,1,'earlier activation fixes the historical loss');
assert.deepEqual(fixed,beta6Duel(config,'gold','green',scenario,20270939,-1));
console.log('PASS: activation delay, no early tick, gauge, season isolation, pursuit removal and former loss replay.');
console.log(JSON.stringify({before:old,after:fixed},null,2));
