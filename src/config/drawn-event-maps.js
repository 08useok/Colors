// The drawn map for this mode and list number, or null (then the mode keeps its usual layouts).
export function drawnEventMap(mode, index) {
  const entry = DRAWN_EVENT_MAPS.find(e => e.index === index && e.modes.includes(mode));
  if (!entry) return null;
  return { ...entry.build(), index: entry.index };
}
